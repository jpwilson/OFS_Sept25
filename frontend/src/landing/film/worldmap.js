const STEP = 5
const r2 = (v) => Math.round(v * 100) / 100

/**
 * The dots, in a viewBox of 360 x 120 (one unit per degree; x = lon + 180, y = 75 - lat).
 * Returns one path string: a small circle per land cell.
 */
export function worldDots(radius = 1.45) {
  let d = ''
  for (const [lat, ranges] of BANDS) {
    for (let lon = -177.5; lon < 180; lon += STEP) {
      if (!ranges.some(([a, b]) => lon >= a - 1.2 && lon <= b + 1.2)) continue
      const x = r2(lon + 180)
      const y = r2(75 - lat)
      d += `M${r2(x - radius)} ${y}a${radius} ${radius} 0 1 0 ${r2(radius * 2)} 0a${radius} ${radius} 0 1 0 ${r2(-radius * 2)} 0`
    }
  }
  return d
}

