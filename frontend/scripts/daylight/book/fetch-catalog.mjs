#!/usr/bin/env node
// Saves the RPI Print catalog entries the photo book uses (owner: book ENGINE).
//
//   node scripts/daylight/book/fetch-catalog.mjs [--no-templates]
//   -> src/daylight/book/engine/data/rpi-catalog.js   (a JS module holding the JSON, so the browser
//      bundle and Node import it the same way, with no JSON import attributes)
//
// BOOKS.md decision 1: the catalog is the source of truth for sizes, page limits, bleed,
// wrap, hinge and spine, and prices. Nothing in the engine types one of those numbers; it
// reads them from the file this script writes. The file keeps:
//   - each product we use, the catalog record verbatim, with the catalog's own generatedAt
//     and the date we fetched it;
//   - the page boxes of RPI's own cover and pages templates for a few page counts, read out
//     of the template PDFs, so tests can check our cover geometry against the printer's
//     templates rather than against our reading of the spec;
//   - the US shipping bands from RPI's public rates document (shipping is charged at cost).
// Sources: https://products.api.rpiprint.com/catalog/v1/products.json
//          https://products.api.rpiprint.com/templates/published/{sku}/{cover|pages}/pdf?units=in&pageCount=N
//          https://open.api.rpiprint.com/shipping/rates
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(HERE, '../../../src/daylight/book/engine/data/rpi-catalog.js')
const CATALOG = 'https://products.api.rpiprint.com/catalog/v1/products.json'
const TEMPLATE = (sku, artifact, n) => `https://products.api.rpiprint.com/templates/published/${sku}/${artifact}/pdf?units=in&pageCount=${n}`
const RATES = 'https://open.api.rpiprint.com/shipping/rates'
const UA = { 'user-agent': 'ofs-book-engine-catalog-fetch' }

// The products we use. Matte laminate cover, 100# dull text: the same print cost as gloss,
// and a dull sheet keeps photos readable under a lamp. Change a SKU here, rerun, and the
// engine follows.
const WANT = [
  { id: 'hc-8x8', label: '8 × 8 in hardcover', launch: true, sku: 'BKPH_HCIW_STD_8.000x8.000IN_80C_MT_40_100T_DUL_44' },
  { id: 'hc-10x8', label: '10 × 8 in hardcover', launch: true, sku: 'BKPH_HCIW_STD_10.000x8.000IN_80C_MT_40_100T_DUL_44' },
  { id: 'hc-8.5x11', label: '8.5 × 11 in hardcover', launch: false, sku: 'BKPH_HCIW_STD_8.500x11.000IN_80C_MT_40_100T_DUL_44' },
  { id: 'sc-8x8', label: '8 × 8 in softcover', launch: false, sku: 'BKPH_SCIW_STD_8.000x8.000IN_10PT_MT_40_100T_DUL_44' },
  { id: 'sc-10x8', label: '10 × 8 in softcover', launch: false, sku: 'BKPH_SCIW_STD_10.000x8.000IN_10PT_MT_40_100T_DUL_44' },
  { id: 'sc-8.5x11', label: '8.5 × 11 in softcover', launch: false, sku: 'BKPH_SCIW_STD_8.500x11.000IN_10PT_MT_40_100T_DUL_44' },
]
const TEMPLATE_COUNTS = [20, 40, 54, 56, 118, 120]

const getJson = async (url) => {
  const r = await fetch(url, { headers: UA })
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`)
  return r.json()
}
const boxesOf = (buf) => {
  const s = buf.toString('latin1')
  const out = {}
  for (const name of ['MediaBox', 'TrimBox', 'BleedBox']) {
    const m = s.match(new RegExp(`/${name}\\s*\\[([^\\]]+)\\]`))
    if (m) out[name] = m[1].trim().split(/\s+/).map((v) => Math.round(parseFloat(v) * 1000) / 1000)
  }
  return out
}

const fetchedAt = new Date().toISOString().slice(0, 10)
const catalog = await getJson(CATALOG)
const bySku = new Map(catalog.products.map((p) => [p.manufacturingSku, p]))
const products = {}
for (const w of WANT) {
  const rec = bySku.get(w.sku)
  if (!rec) throw new Error(`catalog has no ${w.sku}`)
  products[w.id] = { id: w.id, label: w.label, launch: w.launch, record: rec }
}

const templates = {}
if (!process.argv.includes('--no-templates')) {
  for (const id of ['hc-8x8', 'hc-10x8', 'sc-8x8']) {
    const sku = products[id].record.manufacturingSku
    templates[id] = { cover: {}, pages: null }
    for (const n of TEMPLATE_COUNTS) {
      const r = await fetch(TEMPLATE(sku, 'cover', n), { headers: UA })
      if (!r.ok) throw new Error(`cover template ${id} ${n}: HTTP ${r.status}`)
      templates[id].cover[n] = boxesOf(Buffer.from(await r.arrayBuffer()))
    }
    const r = await fetch(TEMPLATE(sku, 'pages', 2), { headers: UA })
    if (!r.ok) throw new Error(`pages template ${id}: HTTP ${r.status}`)
    templates[id].pages = boxesOf(Buffer.from(await r.arrayBuffer()))
  }
}

const rates = await getJson(RATES)
const us = rates.destinationGroups.find((g) => g.code === 'US')
const shipping = { generatedAt: rates.generatedAt, currency: rates.currency, pricingModel: rates.pricingModel, US: us.tiers }

const out = {
  note: 'Generated by scripts/daylight/book/fetch-catalog.mjs from RPI Print\'s public catalog. Do not edit; rerun. Points are 1/72 inch.',
  source: CATALOG,
  catalogGeneratedAt: catalog.generatedAt,
  currency: catalog.currency,
  fetchedAt,
  products,
  templates: { source: 'https://products.api.rpiprint.com/templates/published/{sku}/{cover|pages}/pdf?units=in&pageCount=N (page boxes in points)', boxes: templates },
  shipping: { source: RATES, ...shipping },
}
fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, `// Generated by scripts/daylight/book/fetch-catalog.mjs from RPI Print's public catalog (fetched ${fetchedAt}).\n// Do not edit; rerun the script. Points are 1/72 inch.\nexport default ${JSON.stringify(out, null, 1)}\n`)
console.log(`[book] catalog ${catalog.generatedAt} (fetched ${fetchedAt}): ${Object.keys(products).join(', ')}; templates for ${Object.keys(templates).join(', ') || 'none'} -> ${path.relative(process.cwd(), OUT)}`)
