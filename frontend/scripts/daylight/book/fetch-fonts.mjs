#!/usr/bin/env node
// Downloads the full static TTFs the printed book uses (owner: book ENGINE), BOOKS.md decision 8.
//
//   node scripts/daylight/book/fetch-fonts.mjs
//   -> daylight-public/book/fonts/*.ttf, OFL-*.txt, SOURCES.md
//
// The site ships Latin-subset WOFF2 variable fonts; print needs whole static faces whose
// metrics the line breaker reads. Every file comes from the family's official upstream
// repository, pinned to a commit, and is recorded with its URL and SHA-256 in SOURCES.md.
// All three families are under the SIL Open Font License 1.1; each licence sits beside them.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(HERE, '../../../daylight-public/book/fonts')

const REPOS = {
  literata: { repo: 'googlefonts/literata', sha: '0c2761b727a1b3a7cffd313c37f0f5163dfc7a63', dir: 'fonts/ttf', licence: 'OFL.txt', family: 'Literata' },
  bricolage: { repo: 'ateliertriay/bricolage', sha: '84745e5b96261ae5f8c6c856e262fe78d1d6efdd', dir: 'fonts/ttf', licence: 'OFL.txt', family: 'Bricolage Grotesque' },
  // the upstream DM Mono repository carries no licence file; its OFL text comes from the
  // Google Fonts repository, which ships the same files (ofl/dmmono)
  dmmono: { repo: 'googlefonts/dm-mono', sha: '57fadabfb200a77de2812540026c249dc3013077', dir: 'exports', licence: { repo: 'google/fonts', sha: '5026800714d07231937d92eb4cceabf06e05d74e', file: 'ofl/dmmono/OFL.txt' }, family: 'DM Mono' },
}
// file -> what the book uses it for
const FILES = {
  literata: {
    'Literata-Regular.ttf': 'story text',
    'Literata-Italic.ttf': 'story text in italics, dedication',
    'Literata-Bold.ttf': 'bold words in story text',
    'Literata-BoldItalic.ttf': 'bold italic words in story text',
  },
  bricolage: {
    'BricolageGrotesque12pt-Regular.ttf': 'captions (small optical size)',
    'BricolageGrotesque12pt-SemiBold.ttf': 'small headings, names, map labels',
    'BricolageGrotesque-ExtraBold.ttf': 'section titles and headings',
    'BricolageGrotesque96pt-ExtraBold.ttf': 'the book title and opener titles (display optical size)',
  },
  dmmono: {
    'DMMono-Regular.ttf': 'page numbers',
    'DMMono-Medium.ttf': 'labels: stops, days, dates',
  },
}

const raw = (r, file) => `https://raw.githubusercontent.com/${r.repo}/${r.sha}/${file}`
const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex')
const get = async (url) => {
  const res = await fetch(url, { headers: { 'user-agent': 'ofs-book-engine-font-fetch' } })
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
  return Buffer.from(await res.arrayBuffer())
}

fs.mkdirSync(OUT, { recursive: true })
const rows = []
for (const [key, r] of Object.entries(REPOS)) {
  const licUrl = typeof r.licence === 'string' ? raw(r, r.licence) : raw(r.licence, r.licence.file)
  const lic = await get(licUrl)
  const licName = `OFL-${key}.txt`
  fs.writeFileSync(path.join(OUT, licName), lic)
  rows.push({ file: licName, url: licUrl, sha: sha256(lic), use: `${r.family} licence (SIL OFL 1.1)` })
  for (const [file, use] of Object.entries(FILES[key])) {
    const url = raw(r, `${r.dir}/${file}`)
    const buf = await get(url)
    if (buf.readUInt32BE(0) !== 0x00010000) throw new Error(`${file} is not a TrueType font`)
    fs.writeFileSync(path.join(OUT, file), buf)
    rows.push({ file, url, sha: sha256(buf), use, bytes: buf.length })
  }
}

const md = [
  '# Book fonts: where every file came from',
  '',
  'Generated by `scripts/daylight/book/fetch-fonts.mjs`. Full static TrueType faces for print (the site ships Latin-subset WOFF2, which a printed book cannot use). Each family is under the SIL Open Font License 1.1, whose text sits beside the fonts. Every file is fetched from the family\'s official upstream repository, pinned to a commit.',
  '',
  '| Family | Repository | Commit |',
  '|---|---|---|',
  ...Object.values(REPOS).map((r) => `| ${r.family} | https://github.com/${r.repo} | \`${r.sha}\` |`),
  '',
  '| File | Used for | SHA-256 | Source URL |',
  '|---|---|---|---|',
  ...rows.map((x) => `| \`${x.file}\` | ${x.use} | \`${x.sha.slice(0, 16)}…\` | ${x.url} |`),
  '',
  'Reserved Font Names: the OFL lets these files be embedded in documents (the proof and print PDFs) and redistributed with this app. We do not modify them; a modified version would have to be renamed.',
  '',
]
fs.writeFileSync(path.join(OUT, 'SOURCES.md'), md.join('\n'))
console.log(`[book] fonts: ${rows.length} files -> ${path.relative(process.cwd(), OUT)}`)
for (const x of rows) console.log(`  ${x.file}  ${x.url}`)
