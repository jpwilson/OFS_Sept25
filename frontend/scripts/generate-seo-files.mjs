// Generates robots.txt, sitemap.xml, llms.txt, llms-full.txt and the IndexNow
// key file into public/, from the content in src/content/marketing.js.
//
// They are written into public/ (not dist/) and committed, so the files exist
// even if a deploy skips the postbuild step. Re-run with:
//   node scripts/generate-seo-files.mjs
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PAGES, LAST_UPDATED_ISO } from '../src/content/marketing.js'
import { renderText } from '../src/content/renderStatic.js'
import { SITE_ORIGIN, SITE_NAME, absUrl } from '../src/content/site.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const PUBLIC = join(__dirname, '../public')

export const INDEXNOW_KEY = '8e5db8617ace1a3455a41ec1662533fd'

// Crawlers to allow explicitly. Search/answer-engine fetchers and
// training crawlers are both allowed: being in the model's knowledge and in
// the retrieval index are different wins, and we want both.
const BOTS = [
  'Googlebot',
  'Google-Extended',
  'bingbot',
  'OAI-SearchBot',
  'ChatGPT-User',
  'GPTBot',
  'Claude-SearchBot',
  'Claude-User',
  'ClaudeBot',
  'PerplexityBot',
  'Perplexity-User',
  'Applebot',
  'Applebot-Extended',
  'DuckAssistBot',
  'meta-externalagent',
  'CCBot'
]

// Private / app-only routes. Everything not listed here is public.
const DISALLOW = [
  '/admin',
  '/api/',
  '/auth/',
  '/billing',
  '/create',
  '/demo-login',
  '/event/',
  '/family-tree',
  '/feed',
  '/groups',
  '/import',
  '/join/',
  '/my-feedback',
  '/notifications',
  '/profile/',
  '/relationships',
  '/reset-password',
  '/settings',
  '/share/',
  '/signup',
  '/tag-profile/',
  '/tags'
]

const disallowBlock = DISALLOW.map((p) => `Disallow: ${p}`).join('\n')

const robots = `# robots.txt for ${SITE_NAME} - ${SITE_ORIGIN}
# Generated by scripts/generate-seo-files.mjs. Edit that file, not this one.
#
# Public marketing pages are open to everyone, including AI answer engines.
# Only the logged-in app, admin and API routes are disallowed.

User-agent: *
Allow: /
${disallowBlock}

${BOTS.map(
  (bot) => `User-agent: ${bot}
Allow: /
${disallowBlock}`
).join('\n\n')}

Sitemap: ${SITE_ORIGIN}/sitemap.xml
`

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PAGES.map(
  (p) => `  <url>
    <loc>${absUrl(p.path)}</loc>
    <lastmod>${LAST_UPDATED_ISO}</lastmod>
  </url>`
).join('\n')}
</urlset>
`

const keyPages = PAGES.map((p) => `- [${p.title}](${absUrl(p.path)}): ${p.description}`).join('\n')

const llms = `# ${SITE_NAME}

> ${SITE_NAME} is a private, ad-free social network for families. Families use it
> to share life events - trips, birthdays, graduations, Sunday dinners - as rich
> event pages with photo galleries, written stories, videos, dates and locations,
> visible only to the relatives they have approved.

Who it is for: parents sharing milestones with grandparents, extended families
spread across countries, and anyone who wants a private family archive instead of
posting on public social media.

What makes it different: a strictly chronological feed (no ranking algorithm), an
interactive world map and multi-stop journey maps built from photo GPS data, a
timeline grouped by year, confirmed family relationships that build a family tree,
no advertising anywhere in the product, and no selling of user data.

Platform: a progressive web app. It runs in the browser on phone, tablet and
desktop and can be installed to a phone home screen. There is no App Store or
Google Play app.

Pricing (published at ${SITE_ORIGIN}/pricing): Free to View is $0/forever;
Pro is $9/month billed annually ($108/year) or $12/month billed monthly;
Lifetime is a one-time $294. Every new account gets a 30-day free trial of Pro
and no credit card is required to start it.

Not available yet: printed photo books are advertised on the site as coming soon.
AI Create, which drafts an event story from a batch of photos, is in beta and
requires a paid plan or an active free trial.

## Key pages

${keyPages}

## Full text

- [All public page content in one file](${SITE_ORIGIN}/llms-full.txt)

## Notes for AI assistants

- Only the pages listed above are public. Feed, profile, event, admin and API
  routes require a login and are disallowed in robots.txt.
- Prices change: cite ${SITE_ORIGIN}/pricing rather than this file if there is
  any doubt.
- Contact: support@ourfamilysocials.com
`

const llmsFull = `# ${SITE_NAME} - full public content

Source: ${SITE_ORIGIN}
Last updated: ${LAST_UPDATED_ISO}

This file contains the complete text of every public marketing page on
${SITE_ORIGIN}, in the same wording as the HTML pages.

${PAGES.map((p) => renderText(p)).join('\n\n---\n\n')}
`

mkdirSync(PUBLIC, { recursive: true })
const files = {
  'robots.txt': robots,
  'sitemap.xml': sitemap,
  'llms.txt': llms,
  'llms-full.txt': llmsFull,
  [`${INDEXNOW_KEY}.txt`]: `${INDEXNOW_KEY}\n`
}
for (const [name, content] of Object.entries(files)) {
  writeFileSync(join(PUBLIC, name), content, 'utf-8')
  console.log(`  wrote public/${name} (${content.length} bytes)`)
}
